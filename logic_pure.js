/* данные для PDF из ответов квиза — те же функции, что и на экране */
function reportData(){
  const a = answers, { score: s, level: lv } = assess(a), v = VERDICTS[lv];
  return {
    date: new Date().toLocaleDateString('ru-RU', {day:'2-digit', month:'long', year:'numeric'}),
    score: s,
    verdict: { title: LEVEL_LABEL[lv], text: v.s },
    answersRows: answerLabels(),
    findings: findings(a).map(f => ({ sev:f.sev, title:plain(f.title), body:plain(f.body) })),
    timeline: timeline(a).map(r => ({
      when: r[0]==='now' ? 'уже сейчас' : r[0]==='категория' ? 'при категории' : r[0],
      now: r[0]==='now', what: plain(r[1]), cons: plain(r[2])
    })),
    groups: teamQuestions(a).map(g => ({ who:g.who, qs:g.qs.map(plain) })),
    checklist: checklist(a).map(plain)
  };
}

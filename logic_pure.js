const FOREIGN  = a => a.dbms==='oracle' || a.dbms==='mssql';  // иностранная проприетарная СУБД
const NO_PATCH = a => a.dbms==='oracle';                      // вендор ушёл, обновления недоступны легально
const DB_NAME = a => a.dbms==='oracle'?'Oracle Database':'Microsoft SQL Server';
const CAT_DONE = a => a.cat==='done';
const CAT_UNDONE = a => a.cat==='not_cii'||a.cat==='not_now'||a.cat==='unknown';
const HAS_PROD = a => a.vendor.includes('prod');

function score(a){
  let s = 0;
  // Q1
  s += ({oracle:45, mssql:42, mysql:32, pg:28, registry:0, unknown:25})[a.dbms] || 0;
  // Q2
  s += ({legacy:15, project:22, planning:5})[a.stage] || 0;
  // Q3 (single-select): «не сделано» повышает риск, «проведено» снижает
  let cat = 0;
  if(a.cat==='not_cii'||a.cat==='not_now') cat += 12;
  else if(a.cat==='unknown') cat += 10;
  else if(a.cat==='done') cat -= 12;
  s += cat;
  // Q4
  if(a.vendor.includes('in_reg'))  s += 5;
  if(a.vendor.includes('promise')) s += 8;
  if(a.vendor.includes('unknown')) s += 8;
  if(a.vendor.includes('prod'))    s -= 25;
  return Math.max(0, Math.min(100, Math.round(s)));
}

/* Полоса определяется фактом, а балл затем прижимается к диапазону этой полосы,
   чтобы метка на шкале всегда стояла в той зоне, что и вердикт.
   high 55–100 · mid 30–54 · low 0–29 */
const BAND_RANGE = { high:[55,100], mid:[30,54], low:[0,29] };
function assess(a){
  const raw = score(a);
  const band = level(raw, a);
  const [lo,hi] = BAND_RANGE[band];
  return { score: Math.max(lo, Math.min(hi, raw)), level: band };
}
/* «Высокий» — только если есть нарушение, действующее уже сейчас:
   иностранная СУБД без патчей либо пропущенный срок подачи во ФСТЭК.
   Иначе потолок — «Повышенный», чтобы вердикт не противоречил таблице. */
/* новый объект строится, но категорирование не оформлено — процедурное нарушение,
   действующее уже сейчас, и оно не зависит от того, какая под ним СУБД */
const NEW_OBJ_GAP = a => a.stage==='project' && a.cat!=='done';
const HAS_NOW_VIOLATION = a => NO_PATCH(a) || NEW_OBJ_GAP(a);
/* Полосы риска отражают факт, а не только сумму баллов:
   high — есть нарушение, действующее уже сейчас;
   mid  — сейчас нарушений нет, но есть несоответствие к сроку или открытые вопросы;
   low  — по слою СУБД всё в порядке.
   Смягчающие ответы (категорирование проведено, у вендора есть прод) не могут
   опустить оценку ниже уровня действующего нарушения. */
function level(s, a){
  if(a && HAS_NOW_VIOLATION(a)) return 'high';          // есть нарушение сейчас
  if(a && findings(a).some(f=>f.sev==='high')) return 'mid'; // критичный пункт, но не действующее нарушение
  return s>=30 ? 'mid' : 'low';                          // выше mid без нарушения сейчас не поднимаемся
}

